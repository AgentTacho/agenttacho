import Foundation

/// Font Awesome style of an icon. Each style lives in its own bundled font.
public enum IconStyle: String, CaseIterable, Codable, Sendable, Comparable {
    case solid
    case regular
    case brands

    /// PostScript name of the bundled Font Awesome Free font for this style.
    public var postScriptName: String {
        switch self {
        case .solid: return "FontAwesome7Free-Solid"
        case .regular: return "FontAwesome7Free-Regular"
        case .brands: return "FontAwesome7Brands-Regular"
        }
    }

    /// File name of the bundled font for this style.
    public var fontFileName: String {
        switch self {
        case .solid: return "fa-solid-900.woff2"
        case .regular: return "fa-regular-400.woff2"
        case .brands: return "fa-brands-400.woff2"
        }
    }

    public static func < (lhs: IconStyle, rhs: IconStyle) -> Bool {
        allCases.firstIndex(of: lhs)! < allCases.firstIndex(of: rhs)!
    }
}

/// Reference to one icon as stored in the configuration file: `"style:name"`,
/// for example `"brands:claude"` or `"solid:robot"`.
public struct IconRef: Hashable, Sendable, CustomStringConvertible {
    public var style: IconStyle
    public var name: String

    public init(style: IconStyle, name: String) {
        self.style = style
        self.name = name
    }

    /// Parses `"style:name"`; nil for anything else.
    public init?(_ text: String) {
        let parts = text.split(separator: ":", maxSplits: 1, omittingEmptySubsequences: false)
        guard parts.count == 2, let style = IconStyle(rawValue: String(parts[0])), !parts[1].isEmpty else { return nil }
        self.init(style: style, name: String(parts[1]))
    }

    public var description: String { "\(style.rawValue):\(name)" }
}

/// One icon of the bundled catalog.
public struct IconEntry: Hashable, Sendable, Identifiable {
    public var ref: IconRef
    public var label: String
    /// The character to draw with the style's font.
    public var character: Character
    public var searchTerms: [String]

    public var id: String { ref.description }
    public var name: String { ref.name }
    public var style: IconStyle { ref.style }
}

/// The Font Awesome Free icons bundled with the app (Resources/FontAwesome),
/// generated by `scripts/build-icon-catalog.sh`.
public final class IconCatalog: Sendable {
    public static let shared = IconCatalog()

    /// All entries, sorted by name, then style.
    public let entries: [IconEntry]
    /// Font Awesome version the catalog was generated from.
    public let version: String
    private let byRef: [IconRef: IconEntry]

    init() {
        let url = Bundle.module.url(forResource: "icons", withExtension: "json", subdirectory: "FontAwesome")
        let decoded = url.flatMap { try? Data(contentsOf: $0) }.flatMap { try? JSONDecoder().decode(CatalogFile.self, from: $0) }
        let entries = (decoded?.icons ?? []).compactMap { raw -> IconEntry? in
            guard let style = IconStyle(rawValue: raw.s),
                  let code = UInt32(raw.u, radix: 16), let scalar = Unicode.Scalar(code) else { return nil }
            return IconEntry(ref: IconRef(style: style, name: raw.n), label: raw.l,
                             character: Character(scalar), searchTerms: raw.t)
        }
        self.entries = entries.sorted { ($0.name, $0.style) < ($1.name, $1.style) }
        self.version = decoded?.version ?? "unknown"
        var map: [IconRef: IconEntry] = [:]
        for entry in entries { map[entry.ref] = entry }
        self.byRef = map
    }

    public func icon(for ref: IconRef) -> IconEntry? {
        byRef[ref]
    }

    /// Resolves a configuration value such as `"brands:claude"`.
    public func icon(for text: String) -> IconEntry? {
        IconRef(text).flatMap { byRef[$0] }
    }

    public func contains(_ text: String) -> Bool {
        icon(for: text) != nil
    }

    /// Case-insensitive search over name, label and search terms. An empty
    /// query returns everything. Ranking: exact name, name prefix, name
    /// contains, label contains, search term contains; ties keep catalog order.
    public func search(_ query: String) -> [IconEntry] {
        let q = query.trimmingCharacters(in: .whitespaces).lowercased()
        guard !q.isEmpty else { return entries }
        var ranked: [(rank: Int, index: Int, entry: IconEntry)] = []
        for (index, entry) in entries.enumerated() {
            let name = entry.name.lowercased()
            let rank: Int
            if name == q {
                rank = 0
            } else if name.hasPrefix(q) {
                rank = 1
            } else if name.contains(q) {
                rank = 2
            } else if entry.label.lowercased().contains(q) {
                rank = 3
            } else if entry.searchTerms.contains(where: { $0.lowercased().contains(q) }) {
                rank = 4
            } else {
                continue
            }
            ranked.append((rank, index, entry))
        }
        return ranked.sorted { ($0.rank, $0.index) < ($1.rank, $1.index) }.map(\.entry)
    }

    /// URLs of the bundled font files, for registration with CoreText.
    public var fontURLs: [IconStyle: URL] {
        var urls: [IconStyle: URL] = [:]
        for style in IconStyle.allCases {
            let base = (style.fontFileName as NSString).deletingPathExtension
            let ext = (style.fontFileName as NSString).pathExtension
            if let url = Bundle.module.url(forResource: base, withExtension: ext, subdirectory: "FontAwesome") {
                urls[style] = url
            }
        }
        return urls
    }

    private struct CatalogFile: Decodable {
        let version: String
        let icons: [RawIcon]
    }

    private struct RawIcon: Decodable {
        let n: String
        let l: String
        let u: String
        let s: String
        let t: [String]
    }
}
